/* ────────────────────────────────────────────────────────────────────────────
 * Memento languages: English, Assamese, Hindi, Bengali.
 * The patient and the caregiver share one switch — whichever either of them
 * picks becomes the language of every screen for this household, and it is
 * remembered on the patient profile.
 * ────────────────────────────────────────────────────────────────────────── */

export type LangCode = "en" | "as" | "hi" | "bn";

export const LANGUAGES: Array<{ code: LangCode; english: string; native: string }> = [
  { code: "en", english: "English", native: "English" },
  { code: "as", english: "Assamese", native: "অসমীয়া" },
  { code: "hi", english: "Hindi", native: "हिन्दी" },
  { code: "bn", english: "Bengali", native: "বাংলা" },
];

const ALIASES: Record<string, LangCode> = {
  en: "en", as: "as", hi: "hi", bn: "bn",
  english: "en", assamese: "as", hindi: "hi", bengali: "bn",
};

/** Accepts a code ("as") or an English name ("Assamese") from the profile. */
export function langFromStored(v?: string | null): LangCode | null {
  if (!v) return null;
  return ALIASES[v.trim().toLowerCase()] ?? null;
}

/** Canonical English name stored on the patient profile (readable there). */
export function languageEnglishName(code: LangCode): string {
  return LANGUAGES.find((l) => l.code === code)?.english ?? "English";
}

export function languageNativeName(code: LangCode): string {
  return LANGUAGES.find((l) => l.code === code)?.native ?? "English";
}

export function isLangCode(v: unknown): v is LangCode {
  return v === "en" || v === "as" || v === "hi" || v === "bn";
}

